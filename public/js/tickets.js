const token = localStorage.getItem("tickethub_token");
const list = document.getElementById("tickets-list");
document.getElementById("logout").addEventListener("click", () => {
  localStorage.removeItem("tickethub_token");
  localStorage.removeItem("tickethub_user");
  location.href = "/";
});
async function loadTickets() {
  if (!token) { list.innerHTML = '<p>Please <a href="/login.html">log in</a> to view your bookings.</p>'; return; }
  try {
    const response = await fetch("/api/tickets/mine", {
      headers: { Authorization: `Bearer ${token}` }
    });
    const tickets = await response.json();
    if (!response.ok) throw new Error(tickets.error || "Unable to load tickets.");
    if (!tickets.length) { list.innerHTML = "<p>No paid tickets yet. Browse upcoming events to get started.</p>"; return; }
    list.innerHTML = tickets.map(t => `<article class="ticket-card">
      <span class="status">${t.status.toUpperCase()}</span>
      <h3>${escapeHtml(t.event_name)}</h3>
      <p>${escapeHtml(t.ticket_name)} · ${escapeHtml(t.venue)}</p>
      <p>${new Date(t.event_date).toLocaleString()}</p>
      <p>Ticket reference: <code>${escapeHtml(t.ticket_code)}</code></p>
      <p class="muted">Your QR code is generated by the server when the verified payment integration is enabled.</p>
    </article>`).join("");
  } catch (error) { list.textContent = error.message; }
}
function escapeHtml(v) { return String(v).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c])); }
loadTickets();
